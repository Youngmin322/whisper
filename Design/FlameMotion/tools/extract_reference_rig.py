"""Extract a common deformation cage from the existing walking masks.
Only motion data is emitted; no character artwork is generated or modified.
"""
from pathlib import Path
import json
import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[3]
COUNT = 24
TIPS = [(128,38)]*3+[(53,52)]*3+[(14,72)]*2+[(29,133)]*3+[(12,83)]*2+[(71,46)]*3
ORIGIN = np.array([63.,38.])
EXTENT = np.array([120.,161.])

def sampled_contour(a, tip):
    edges={}
    def add(s,e): edges.setdefault(s,[]).append(e)
    for y,x in zip(*np.nonzero(a)):
        if y==0 or not a[y-1,x]: add((x,y),(x+1,y))
        if x==249 or not a[y,x+1]: add((x+1,y),(x+1,y+1))
        if y==249 or not a[y+1,x]: add((x+1,y+1),(x,y+1))
        if x==0 or not a[y,x-1]: add((x,y+1),(x,y))
    loops=[]
    while edges:
        start=next(iter(edges)); point=start; loop=[]
        while point in edges:
            loop.append(point); nxt=edges[point].pop()
            if not edges[point]: del edges[point]
            point=nxt
            if point==start: break
        loops.append(loop)
    points=np.array(max(loops,key=len),dtype=float)
    tip=np.array(tip); start=np.argmin(((points-tip)**2).sum(axis=1))
    points=np.roll(points,-start,axis=0); points=np.vstack((points,points[0]))
    lengths=np.concatenate(([0.],np.cumsum(np.linalg.norm(np.diff(points,axis=0),axis=1))))
    distances=np.arange(COUNT)*lengths[-1]/COUNT
    sampled=np.column_stack([np.interp(distances,lengths,points[:,c]) for c in range(2)])
    return sampled

def contour(frame):
    a = np.asarray(Image.open(ROOT/f'Whisper/Assets.xcassets/FlameStepOuter{frame:02}.imageset/FlameStepOuter{frame:02}.png'))[:,:,3]>128
    return (sampled_contour(a,TIPS[frame])-ORIGIN)/EXTENT

def approved_contour():
    a=np.asarray(Image.open(ROOT/'Whisper/Assets.xcassets/EmotionFlameJoyBody.imageset/EmotionFlameJoyBody.png'))[:,:,3]>128
    ys,xs=np.nonzero(a); origin=np.array([xs.min(),ys.min()],float)
    extent=np.array([xs.max()-xs.min()+1,ys.max()-ys.min()+1],float)
    tip=(xs[ys.argmin()],ys.min())
    return (sampled_contour(a,tip)-origin)/extent

def radial(delta):
    r2=(delta*delta).sum(axis=-1)
    return .5*r2*np.log(np.maximum(r2,1e-12))

reference_source=contour(0)
source=approved_contour()
frames=[]
for frame in range(16):
    angle = -12 if 3<=frame<=7 else -28 if 8<=frame<=10 else -18 if 11<=frame<=12 else 0
    scale=.82 if 8<=frame<=10 else .90 if 11<=frame<=12 else 1
    # Preserve the approved silhouette as the canonical frame. Apply only the
    # displacement from the committed gait so frame zero remains pixel exact.
    target=source+(contour(frame)-reference_source)
    n=len(target); k=radial(target[:,None]-target[None,:]); p=np.column_stack((np.ones(n),target))
    matrix=np.block([[k+np.eye(n)*1e-7,p],[p.T,np.zeros((3,3))]])
    solution=np.linalg.solve(matrix,np.vstack((source,np.zeros((3,2)))))
    mapping=np.concatenate((np.column_stack((target,solution[:n])).reshape(-1),solution[n:].reshape(-1)))
    frames.append(dict(frame=frame,rotation=angle,source=source.tolist(),target=target.tolist(),mapping=mapping.tolist()))

(ROOT/'Design/FlameMotion/reference-rig.json').write_text(json.dumps(dict(controlCount=len(source),frames=frames),indent=2)+'\n')
lines=['// Generated by Design/FlameMotion/tools/extract_reference_rig.py.\n// Inverse TPS mappings transfer the committed 16-frame gait to approved artwork.\nimport Foundation\n\nstruct FlameReferencePose {\n    let faceRotation: Double\n    let faceScale: CGFloat\n    let mapping: [Float]\n}\n\nenum FlameReferenceRig {\n    static let controlCount = %d\n    static let frames: [FlameReferencePose] = ['%len(source)]
for f in frames:
    scale=.82 if 8<=f['frame']<=10 else .90 if 11<=f['frame']<=12 else 1
    lines.append('        .init(faceRotation: %d, faceScale: %.2f, mapping: [%s]),'%(f['rotation'],scale,', '.join('%.9f'%v for v in f['mapping'])))
lines.append('    ]\n}\n');(ROOT/'Whisper/FlameReferenceRig.swift').write_text('\n'.join(lines))
print('Extracted 16 poses with',len(source),'corresponding controls each')
